"""Layout model for the template builder: validate a layout and generate its preset files.

A layout is the source of truth (``layout.json``); ``generate`` turns it into the
``template.html`` / ``style.css`` / ``meta.json`` that the renderer reads.
"""

from __future__ import annotations

import json
import re
import tempfile
from contextlib import contextmanager
from pathlib import Path

from PIL import Image

from app.core.config import atomic_write_text
from app.core.template_renderer import (
    DEFAULT_DPI,
    EXAMPLES_ROOT,
    TemplatePreset,
    find_thermal_black_block,
    list_presets,
    render_records,
)

MODES = ("positions", "inventory")
ELEMENT_TYPES = ("text", "barcode", "qr", "box", "line")

SAMPLE_RECORDS: dict[str, dict[str, str]] = {
    "positions": {
        "code": "H029A",
        "barcode_data": "C001H029A",
        "visible_text": "H-029-A",
        "warehouse_prefix": "C001",
        "user_text": "AISLE H",
    },
    "inventory": {
        "sku": "SKU-12345",
        "name": "Sample product name 500 ml",
        "client": "Client Ltd",
        "batch": "B-240815",
        "expiry": "2027-05-31",
        "position_code": "H-029-A",
        "position_data": "C001H029A",
        "generated_date": "2026/10/28",
        "quantity": "3",
    },
}

# Single braces only: `{{x}}` is literal text, not a placeholder named x.
_PLACEHOLDER = re.compile(r"(?<!\{)\{([a-z_]+)\}(?!\})")

HEADER = (
    "GENERATED by the template builder from layout.json - edit this label in the app "
    "(Template > Edit...). Hand edits here are lost on the next Save. Folders named like "
    "a shipped preset are app-owned and rewritten on launch. See ../README.txt"
)

_JUSTIFY = {"left": "flex-start", "center": "center", "right": "flex-end"}


def mode_fields(mode: str) -> list[str]:
    return list(SAMPLE_RECORDS[mode])


def new_layout(mode: str) -> dict:
    return {"name": "", "mode": mode, "width_mm": 150, "height_mm": 100, "elements": []}


def default_element(type_: str, mode: str, x_mm: float = 2, y_mm: float = 2) -> dict:
    base = {"type": type_, "x_mm": x_mm, "y_mm": y_mm}
    field = "barcode_data" if mode == "positions" else "sku"
    if type_ == "text":
        return {
            **base,
            "w_mm": 40,
            "h_mm": 8,
            "content": "Text",
            "max_mm": 5,
            "min_mm": 2,
            "wrap": False,
            "bold": False,
            "uppercase": False,
            "align": "left",
            "letter_spacing_mm": 0,
        }
    if type_ == "barcode":
        return {**base, "w_mm": 50, "h_mm": 12, "field": field}
    if type_ == "qr":
        return {**base, "w_mm": 20, "h_mm": 20, "field": field}
    if type_ == "box":
        return {**base, "w_mm": 30, "h_mm": 20, "thickness_mm": 0.4}
    if type_ == "line":
        return {**base, "w_mm": 40, "h_mm": 0, "orientation": "h", "thickness_mm": 0.3}
    raise ValueError(f"unknown element type {type_!r}")


def placeholders(content: str) -> list[str]:
    return _PLACEHOLDER.findall(content)


def _number(value, key: str, minimum: float) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ValueError(f"{key} must be a number, got {value!r}")  # noqa: TRY004 - ValueError is the contract
    if value < minimum:
        raise ValueError(f"{key} must be {minimum:g} or more, got {value!r}")
    return value


def _size(value, key: str) -> float:
    value = _number(value, key, 10)
    if value > 300:
        raise ValueError(f"{key} must be 300 mm or less, got {value!r}")
    return value


def _thickness(value) -> float:
    return min(max(_number(value, "thickness_mm", 0), 0.3), 0.5)


def _element(raw, mode: str) -> dict:
    if not isinstance(raw, dict):
        raise ValueError("every element must be an object")  # noqa: TRY004 - ValueError is the contract
    type_ = raw.get("type")
    if type_ not in ELEMENT_TYPES:
        raise ValueError(f"unknown element type {type_!r}")
    el = default_element(type_, mode)
    for key in el:
        if key in raw:
            el[key] = raw[key]

    el["x_mm"] = _number(el["x_mm"], "x_mm", 0)
    el["y_mm"] = _number(el["y_mm"], "y_mm", 0)
    if type_ == "line":
        if el["orientation"] not in ("h", "v"):
            raise ValueError(f"orientation must be h or v, got {el['orientation']!r}")
        axis, other = ("w_mm", "h_mm") if el["orientation"] == "h" else ("h_mm", "w_mm")
        el[axis] = _number(el[axis], axis, 1)
        el[other] = 0
        el["thickness_mm"] = _thickness(el["thickness_mm"])
    else:
        el["w_mm"] = _number(el["w_mm"], "w_mm", 1)
        el["h_mm"] = _number(el["h_mm"], "h_mm", 1)
    if type_ == "box":
        el["thickness_mm"] = _thickness(el["thickness_mm"])
    elif type_ == "text":
        _check_text(el, mode)
    elif type_ in ("barcode", "qr") and el["field"] not in mode_fields(mode):
        raise ValueError(f"field {el['field']!r} is not a {mode} field")
    return el


def _check_text(el: dict, mode: str) -> None:
    if not isinstance(el["content"], str):
        raise ValueError("content must be text")  # noqa: TRY004 - ValueError is the contract
    for name in placeholders(el["content"]):
        if name not in mode_fields(mode):
            raise ValueError(f"unknown placeholder {{{name}}} in text content")
    el["min_mm"] = _number(el["min_mm"], "min_mm", 0)
    el["max_mm"] = _number(el["max_mm"], "max_mm", 0)
    if el["min_mm"] <= 0 or el["min_mm"] > el["max_mm"]:
        raise ValueError("min_mm must be above 0 and no more than max_mm")
    if el["align"] not in ("left", "center", "right"):
        raise ValueError(f"align must be left, center or right, got {el['align']!r}")
    el["letter_spacing_mm"] = _number(el["letter_spacing_mm"], "letter_spacing_mm", 0)
    for flag in ("wrap", "bold", "uppercase"):
        el[flag] = bool(el[flag])


def normalise_layout(data: dict) -> dict:
    mode = data.get("mode")
    if mode not in MODES:
        raise ValueError(f"mode must be one of {', '.join(MODES)}, got {mode!r}")
    name = data.get("name", "")
    if not isinstance(name, str):
        raise ValueError("name must be text")  # noqa: TRY004 - ValueError is the contract
    elements = data.get("elements", [])
    if not isinstance(elements, list):
        raise ValueError("elements must be a list")  # noqa: TRY004 - ValueError is the contract
    return {
        "name": name,
        "mode": mode,
        "width_mm": _size(data.get("width_mm", 150), "width_mm"),
        "height_mm": _size(data.get("height_mm", 100), "height_mm"),
        "elements": [_element(raw, mode) for raw in elements],
    }


def slugify(name: str) -> str:
    return re.sub(r"[\W_]+", "-", name.lower()).strip("-")


def _n(value) -> str:
    return f"{value:g}"


def _mm(value) -> str:
    return f"{value:g}mm"


def _type_rules(el: dict) -> str:
    kind = el["type"]
    if kind == "text":
        rules = [
            "align-items: center;",
            f"justify-content: {_JUSTIFY[el['align']]};",
            f"text-align: {el['align']};",
        ]
        if el["bold"]:
            rules.append("font-weight: 700;")
        if el["uppercase"]:
            rules.append("text-transform: uppercase;")
        if el["letter_spacing_mm"] > 0:
            rules.append(f"letter-spacing: {_mm(el['letter_spacing_mm'])};")
        if el["wrap"]:
            rules.append("line-height: 1.25; word-wrap: break-word;")
        else:
            rules.append("white-space: nowrap; line-height: 1;")
        return " ".join(rules)
    if kind == "box":
        return f"border: {_mm(el['thickness_mm'])} solid #000;"
    if kind == "line" and el["orientation"] == "h":
        return f"height: 0; border-top: {_mm(el['thickness_mm'])} solid #000;"
    if kind == "line":
        return f"width: 0; border-left: {_mm(el['thickness_mm'])} solid #000;"
    return ""


def _style_css(layout: dict) -> str:
    width, height = _mm(layout["width_mm"]), _mm(layout["height_mm"])
    lines = [
        f"/* {HEADER} */",
        f"@page {{ size: {width} {height}; margin: 0; }}",
        "html, body { margin: 0; padding: 0; }",
        (
            f".label {{ position: relative; box-sizing: border-box; width: {width}; height: {height}; "
            'background: #fff; color: #000; font-family: "JetBrains Mono", monospace; overflow: hidden; }'
        ),
        ".el { position: absolute; box-sizing: border-box; display: flex; overflow: hidden; }",
        ".el img { width: 100%; height: 100%; }",
    ]
    for i, el in enumerate(layout["elements"]):
        lines.append(
            f".e{i} {{ left: {_mm(el['x_mm'])}; top: {_mm(el['y_mm'])}; "
            f"width: {_mm(el['w_mm'])}; height: {_mm(el['h_mm'])}; {_type_rules(el)} }}"
        )
    return "\n".join(lines) + "\n"


def _text_element(i: int, el: dict) -> list[str]:
    parts = []
    for n, piece in enumerate(_PLACEHOLDER.split(el["content"])):
        if n % 2:
            parts.append("{{ " + piece + " }}")
        elif piece:
            parts.append("{{ " + json.dumps(piece, ensure_ascii=False) + " }}")
    var = f"t{i}"
    box_w, box_h = el["w_mm"] - 1, el["h_mm"] - 0.5
    if el["wrap"]:
        fit = (
            f"label_tools.fit_font_block({var}, {_n(box_w)}, {_n(box_h)}, "
            f"{_n(el['max_mm'])}, {_n(el['min_mm'])})"
        )
    else:
        fit = (
            f"label_tools.fit_font({var}, {_n(box_w)}, {_n(min(el['max_mm'], el['h_mm']))}, "
            f"{_n(el['min_mm'])}, letter_spacing_mm={_n(el['letter_spacing_mm'])})"
        )
    return [
        "{% set "
        + var
        + " %}"
        + "".join(parts)
        + "{% endset %}"
        + f'<div class="el e{i}" style="font-size: {{{{ {fit} }}}}mm">{{{{ {var}|e }}}}</div>'
    ]


def _template_html(layout: dict) -> str:
    lines = ["{# " + HEADER + " #}", '<div class="label">']
    for i, el in enumerate(layout["elements"]):
        if el["type"] == "text":
            lines += _text_element(i, el)
        elif el["type"] in ("barcode", "qr"):
            field = el["field"]
            helper = "barcode" if el["type"] == "barcode" else "qr_code"
            lines.append(
                f'<div class="el e{i}">{{% if {field} %}}<img src="{{{{ label_tools.{helper}({field}) }}}}">'
                "{% endif %}</div>"
            )
        else:
            lines.append(f'<div class="el e{i}"></div>')
    lines.append("</div>")
    return "\n".join(lines) + "\n"


def generate(layout: dict) -> dict[str, str]:
    layout = normalise_layout(layout)
    meta = {
        "name": layout["name"],
        "width_mm": layout["width_mm"],
        "height_mm": layout["height_mm"],
    }
    return {
        "template.html": _template_html(layout),
        "style.css": _style_css(layout),
        "meta.json": json.dumps(meta, ensure_ascii=False),
    }


def is_app_owned(mode: str, slug: str) -> bool:
    return (EXAMPLES_ROOT / mode / slug).is_dir()


def load_layout(folder: Path) -> dict:
    try:
        data = json.loads((folder / "layout.json").read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        raise ValueError(f"Could not read layout.json in {folder.name}: {error}") from error
    if not isinstance(data, dict):
        raise ValueError(f"layout.json in {folder.name} must be an object")  # noqa: TRY004 - ValueError is the contract
    return normalise_layout(data)


def check_save_target(shared_folder: Path, layout: dict, edit_folder: Path | None) -> Path:
    layout = normalise_layout(layout)
    name, mode = layout["name"], layout["mode"]
    slug = slugify(name)
    if not slug:
        raise ValueError("Use at least one letter or digit in the name.")
    mode_dir = Path(shared_folder) / "templates" / mode
    if edit_folder is not None:
        if is_app_owned(mode, edit_folder.name):
            raise ValueError(f'"{name}" is a built-in template - save a copy under another name.')
        target = edit_folder
    else:
        if is_app_owned(mode, slug):
            raise ValueError(f'"{name}" is a built-in template name - pick another name.')
        if (mode_dir / slug).exists():
            raise ValueError(f'A template folder named "{slug}" already exists - pick another name.')
        target = mode_dir / slug
    for preset in list_presets(shared_folder, mode):
        if preset.name == name and preset.template_path.parent.resolve() != target.resolve():
            raise ValueError(f'Another template is already called "{name}" - pick another name.')
    return target


def save_layout(layout: dict, folder: Path) -> None:
    layout = normalise_layout(layout)
    atomic_write_text(folder / "layout.json", json.dumps(layout, indent=2, ensure_ascii=False) + "\n")
    for filename, content in generate(layout).items():
        atomic_write_text(folder / filename, content)


def sample_for(mode: str, record: dict | None) -> dict:
    return {**SAMPLE_RECORDS[mode], **(record or {})}


@contextmanager
def _temp_preset(layout: dict):
    layout = normalise_layout(layout)
    with tempfile.TemporaryDirectory() as tmp:
        folder = Path(tmp)
        save_layout(layout, folder)
        yield TemplatePreset(
            layout["name"],
            layout["mode"],
            layout["width_mm"],
            layout["height_mm"],
            folder / "template.html",
            folder / "style.css",
        )


def render_sample(layout: dict, record: dict | None) -> Image.Image:
    with _temp_preset(layout) as preset:
        return render_records(preset, [sample_for(preset.mode, record)])[0]


def black_block_mm(layout: dict, record: dict | None) -> tuple[float, float] | None:
    with _temp_preset(layout) as preset:
        found = find_thermal_black_block(preset, [sample_for(preset.mode, record)])
    if found is None:
        return None
    _, x, y = found
    return round(x * 25.4 / DEFAULT_DPI, 1), round(y * 25.4 / DEFAULT_DPI, 1)


def regenerate_shipped() -> list[Path]:
    folders = []
    for mode in MODES:
        for layout_path in sorted((EXAMPLES_ROOT / mode).glob("*/layout.json")):
            folder = layout_path.parent
            save_layout(load_layout(folder), folder)
            folders.append(folder)
    return folders


if __name__ == "__main__":
    regenerate_shipped()
